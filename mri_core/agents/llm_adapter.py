"""Offline-only adapter interface for a future reviewer-brief LLM (e.g. Nebius/NVIDIA
Nemotron, or an AMD-supported model). No external model is invoked anywhere in this
module -- only a deterministic, in-process OfflineStubAdapter is provided, for tests
and local development. No API keys or hardcoded endpoints exist anywhere in this file.

Design, explained plainly: a keyword/regex screen can never prove that a sentence of
free text is factually correct -- it can only catch the most obvious disallowed claim
types (a diagnosis, a certainty claim, an invented approval). This module therefore
never promotes free text to "verified evidence," regardless of what it contains:

  - render_reviewer_brief() produces the only TRUSTED output type (ReviewerBrief). Its
    summary_text is always generated by this package's own fixed template from fields
    that already exist on the EvidenceBundle/ConsensusResult -- no adapter output is
    ever substituted into it.
  - An adapter's actual output (RawProposal, free text + claimed citations) is run
    through screen_proposal(), which can only return BLOCKED (an automated check
    failed outright) or QUARANTINED (every automated check passed, but the text is
    still unverified and is held for explicit human consideration). There is no code
    path anywhere in this module that turns a QUARANTINED proposal into verified
    evidence.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from enum import Enum
from typing import Protocol, Tuple

from .consensus import ConsensusResult
from .contracts import EvidenceBundle

MAX_PROPOSAL_LENGTH = 500

# Conservative, explicitly non-semantic blocklist. Matching one of these patterns is
# sufficient to BLOCK a proposal outright; NOT matching any of them is NOT proof the
# proposal is factually supported -- it only means the most obvious disallowed claim
# types were not detected by this cheap pattern check.
_FORBIDDEN_PATTERNS: Tuple[re.Pattern, ...] = tuple(
    re.compile(p, re.IGNORECASE)
    for p in (
        r"\bdiagnos\w*",
        r"\bi\s+confirm\b",
        r"\bapproved\s+by\b",
        r"\bclinician\w*\s+(approved|reviewed|confirmed|signed\s*off)",
        r"\bdefinite(ly)?\b",
        r"\bconfirmed\b",
        r"\brule(d)?\s+out\b",
        r"\bis\s+(positive|negative)\s+for\b",
        r"\bpatient\s+has\b",
        r"\bthe\s+patient\s+shows\b",
    )
)


class ProposalStatus(str, Enum):
    BLOCKED = "BLOCKED"  # an automated check failed outright; rejected
    QUARANTINED = "QUARANTINED"  # every automated check passed, but still unverified free text


class LLMAdapterError(Exception):
    """Raised when a trusted ReviewerBrief itself fails validation (not for proposal
    screening -- see screen_proposal(), which never raises, only classifies)."""


@dataclass(frozen=True)
class ReviewerBrief:
    """The only TRUSTED output type in this module. summary_text is always produced by
    render_reviewer_brief()'s fixed template -- never substituted from an adapter's
    free text. Carries no probabilities, provenance, quality-status, or review-state
    fields, so it cannot structurally override any of those regardless of what any
    future adapter implementation does."""

    summary_text: str
    cited_evidence: Tuple[str, ...]
    disclaimer: str

    def to_dict(self) -> dict:
        return {
            "summary_text": self.summary_text,
            "cited_evidence": list(self.cited_evidence),
            "disclaimer": self.disclaimer,
        }


@dataclass(frozen=True)
class RawProposal:
    """What an LLMAdapter actually returns: untrusted free text plus claimed
    citations. Never treated as verified evidence -- see screen_proposal()."""

    raw_text: str
    cited_evidence: Tuple[str, ...]


@dataclass(frozen=True)
class QuarantinedProposal:
    """The result of screening a RawProposal. BLOCKED means an automated check failed
    outright (reason explains which). QUARANTINED means every automated check passed
    but the text is still unverified free text, held for explicit human consideration
    -- it is never published as verified evidence by anything in this module."""

    status: ProposalStatus
    raw_text: str
    reason: str
    cited_evidence: Tuple[str, ...]

    def to_dict(self) -> dict:
        return {
            "status": self.status.value,
            "raw_text": self.raw_text,
            "reason": self.reason,
            "cited_evidence": list(self.cited_evidence),
        }


class LLMAdapter(Protocol):
    """Interface a future Nebius/Nemotron or AMD-backed adapter must implement. Returns
    untrusted free text (RawProposal), never a trusted ReviewerBrief directly -- only
    this module's own render_reviewer_brief() can produce a ReviewerBrief."""

    def propose(self, bundle: EvidenceBundle, consensus: ConsensusResult) -> RawProposal:
        ...


class OfflineStubAdapter:
    """Deterministic, offline fake transport. Never makes a network call, never reads
    an API key or endpoint from the environment. Its proposal only restates fields
    already present on the bundle/consensus -- it still goes through screen_proposal()
    like any other adapter's output and is still quarantined, never auto-trusted."""

    def propose(self, bundle: EvidenceBundle, consensus: ConsensusResult) -> RawProposal:
        text = (
            f"Workflow status is {consensus.workflow_status.value}. "
            f"{bundle.model_count} model(s) were used. Quality gate: {bundle.quality_gate_status.value}."
        )
        return RawProposal(raw_text=text, cited_evidence=bundle.evidence_references)


def screen_proposal(proposal: RawProposal, bundle: EvidenceBundle) -> QuarantinedProposal:
    """Run every automated check this package can perform. Returns BLOCKED if any
    check fails outright, otherwise QUARANTINED -- there is no "verified" outcome.

    Checks, in order: non-empty text, length bound, forbidden-claim patterns
    (diagnosis / certainty / invented approval -- explicitly not semantic
    verification), and citation support (every cited_evidence entry must already
    appear in bundle.evidence_references).
    """
    text = proposal.raw_text
    if not isinstance(text, str) or not text.strip():
        return QuarantinedProposal(ProposalStatus.BLOCKED, text, "Empty or non-string proposal text.", proposal.cited_evidence)

    if len(text) > MAX_PROPOSAL_LENGTH:
        return QuarantinedProposal(
            ProposalStatus.BLOCKED, text, f"Proposal exceeds max length {MAX_PROPOSAL_LENGTH} characters.",
            proposal.cited_evidence,
        )

    for pattern in _FORBIDDEN_PATTERNS:
        if pattern.search(text):
            return QuarantinedProposal(
                ProposalStatus.BLOCKED, text,
                f"Matched a disallowed claim pattern ({pattern.pattern!r}): diagnosis, clinical certainty, "
                "or invented reviewer approval language is never permitted in a proposal.",
                proposal.cited_evidence,
            )

    unsupported = [ref for ref in proposal.cited_evidence if ref not in bundle.evidence_references]
    if unsupported:
        return QuarantinedProposal(
            ProposalStatus.BLOCKED, text, f"Cites evidence not present in the bundle (unsupported claim): {unsupported!r}",
            proposal.cited_evidence,
        )

    return QuarantinedProposal(
        ProposalStatus.QUARANTINED, text,
        "Passed automated screening (non-empty, length, forbidden-pattern, and citation-support checks), "
        "but free text cannot be verified as factually supported by keyword/regex matching alone. "
        "Quarantined for explicit human review; never published as verified evidence by this package.",
        proposal.cited_evidence,
    )


def render_reviewer_brief(bundle: EvidenceBundle, consensus: ConsensusResult) -> ReviewerBrief:
    """The only way to produce a trusted ReviewerBrief: a fixed template populated
    exclusively from fields that already exist on bundle/consensus. No free text, from
    an LLM adapter or anywhere else, is ever substituted into this output.
    """
    short_uid = bundle.study_uid[:16] + ("..." if len(bundle.study_uid) > 16 else "")
    summary = (
        f"Workflow status: {consensus.workflow_status.value}. "
        f"Study: {short_uid}. "
        f"{bundle.model_count} model(s) used, ensemble={bundle.is_ensemble}. "
        f"Quality gate: {bundle.quality_gate_status.value}. "
        f"Critic findings: {len(consensus.critic_findings)}."
    )
    return ReviewerBrief(summary_text=summary, cited_evidence=bundle.evidence_references, disclaimer=bundle.disclaimer)


def validate_reviewer_brief(brief: ReviewerBrief, bundle: EvidenceBundle) -> None:
    """Strict structural validation of a *trusted* ReviewerBrief (i.e. one produced by
    render_reviewer_brief(), never one built from raw adapter free text). Raises
    LLMAdapterError if the brief is empty/malformed or cites evidence not present in
    the bundle. This is a defensive check on this package's own template output, not a
    way to validate arbitrary free text -- use screen_proposal() for that.
    """
    if not isinstance(brief.summary_text, str) or not brief.summary_text.strip():
        raise LLMAdapterError("Reviewer brief summary_text must be non-empty text.")
    if len(brief.summary_text) > MAX_PROPOSAL_LENGTH:
        raise LLMAdapterError(f"Reviewer brief summary_text exceeds max length {MAX_PROPOSAL_LENGTH}.")
    if not isinstance(brief.disclaimer, str) or not brief.disclaimer.strip():
        raise LLMAdapterError("Reviewer brief disclaimer must be non-empty text.")
    unsupported = [ref for ref in brief.cited_evidence if ref not in bundle.evidence_references]
    if unsupported:
        raise LLMAdapterError(
            f"Reviewer brief cites evidence not present in the bundle (unsupported claim): {unsupported!r}"
        )
